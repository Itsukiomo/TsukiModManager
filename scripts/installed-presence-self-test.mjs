import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";

const source = fs.readFileSync("src/pages/Installed/InstalledPage.tsx", "utf8");
const ast = ts.createSourceFile("InstalledPage.tsx", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const fn = ast.statements.find((node) => ts.isFunctionDeclaration(node) && node.name?.text === "receiptMatchFromInstalledState");
assert(fn);
const context = vm.createContext({});
vm.runInContext(ts.transpileModule(fn.getText(ast), { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText, context);
const record = { source: "modworkshop", id: "123", uid: "receipt", receiptId: "receipt", filename: "Example.pak", enabled: false, files: [{ fileName: "Example.pak", relativePath: "Example.pak", live: false }] };
assert.equal(context.receiptMatchFromInstalledState(record).installed, false);
assert.equal(context.receiptMatchFromInstalledState(record).missing, true);
record.files[0].live = true;
assert.equal(context.receiptMatchFromInstalledState(record).installed, true);
assert.equal(context.receiptMatchFromInstalledState(record).enabled, false);
assert(/initialRefreshTimerRef\.current = window\.setTimeout\([\s\S]*?void refreshInstalled\(\);[\s\S]*?\}, 0\);/.test(source), "Entry must immediately revalidate disk presence");
const refresh = source.slice(source.indexOf('async function refreshInstalled'), source.indexOf('async function runPairing'));
assert(!refresh.includes('"list_source_index"'), "Installed must not transfer the entire source catalog");
assert(refresh.indexOf('setScanResult(scan)') < refresh.indexOf('"match_installed_source_index_v2"'), "Live files must render before full source identification");
assert(refresh.includes('invoke<InstalledStateRecord[]>("list_installed_state_records", { profileId })'), "Fast loading must retain live receipt validation");
assert(source.includes('window.addEventListener("focus", reconcileOnFocus)'), "Returning from external file deletion must reconcile");
assert(source.includes('if (!(record.files ?? []).some((file) => file.live)) continue;'));

const depsSource = fs.readFileSync("src/models/dependency.ts", "utf8");
const depsAst = ts.createSourceFile("dependency.ts", depsSource, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
const depsJs = ts.transpileModule(depsAst.statements.filter((node) => !ts.isImportDeclaration(node)).map((node) => node.getText(depsAst)).join("\n"), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const deps = vm.createContext({ exports: {}, catalogJson: JSON.parse(fs.readFileSync("src/data/dependencies.json", "utf8")) });
vm.runInContext(depsJs, deps);
const ue5 = deps.exports.dependenciesForProfile("builtin.payday3", "UE5.5");
const ue4 = deps.exports.dependenciesForProfile("builtin.payday3", "UE4.27");
assert.equal(ue5.length, 1);
assert.equal(ue5[0].modworkshop.modId, "47771");
assert.equal(deps.exports.findDependency("UE4SS", "builtin.payday3", "UE5.5").id, "pd3-ue5-ue4ss-allow-pak");
assert.equal(deps.exports.findDependency("Logic Mod Loader", "builtin.payday3", "UE5.5"), null);
assert.equal(deps.exports.findDependency("UE4SS", "builtin.payday3", "UE4.27").id, "pd3-ue4ss");
assert(ue4.some((dep) => dep.id === "pd3-logic-mod-loader"));
assert(!ue4.some((dep) => dep.id === "pd3-ue5-ue4ss-allow-pak"));
console.log("Installed presence and PAYDAY 3 version-specific dependency tests passed.");
